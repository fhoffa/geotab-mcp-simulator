#!/usr/bin/env node
"use strict";
// Offline public-demo contracts. No credentials, live queries or private fixtures.
const assert = require("assert");
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const root = path.join(__dirname, "..");
const ctx = vm.createContext({ window: {} });
["data/sample-data.js", "data/conversations.js"].forEach(f => vm.runInContext(fs.readFileSync(path.join(root, f), "utf8"), ctx));
const main = ctx.window.CONVERSATIONS, graph = ctx.window.ALTITUDE_CONVERSATIONS;
const d = ctx.window.SAMPLE_DATA.altitude;
assert.strictEqual(graph.start, "altitude");
assert.strictEqual(d.fictional, true);
const intro = graph.nodes.altitude.events;
assert(intro[0].text.includes("pending review and approval with the Altitude team"));
assert(intro[0].text.includes("fictional teaching examples"));
const setup = intro[1].text;
["User Management", "API Access", "Generate API Key", "Authorization: Bearer <your-api-key>", "Never paste keys or passwords", "needs no credentials"].forEach(s => assert(setup.includes(s)));
["https://altitude.geotab.com/", "https://altitudeportal.geotab.com", "https://altitudehelp.geotab.com/api-guide/getting-started/before-you-begin#Getting-Altitude-Credentials"].forEach(url => assert(setup.includes(url)));
const mainIds = Object.keys(main.nodes), ids = Object.keys(graph.nodes);
mainIds.forEach(id => {
  assert(!/^altitude/.test(id));
  const n = main.nodes[id];
  [n.next, ...(n.choices || []).map(c => c.next)].filter(Boolean).forEach(to => assert(main.nodes[to], "Main dialog exposes another graph"));
});
ids.forEach(id => {
  assert(/^altitude(?:-|$)/.test(id) && !main.nodes[id]);
  const n = graph.nodes[id];
  assert(!n.db, "Altitude must not display a MyGeotab database badge");
  [n.next, ...(n.choices || []).map(c => c.next)].filter(Boolean).forEach(to => assert(graph.nodes[to], "Altitude exits into the MCP graph"));
  (n.choices || []).forEach(c => assert(!c.action || c.action === "restart"));
});
const material = JSON.stringify({ graph, d });
assert(!/(?:git|jira|datahub)\.geotab\.com|docs\.google\.com|\/home\/|\/workspace\/|its_\d{10,}|glpat-|-----BEGIN.*PRIVATE KEY/.test(material), "Non-public artifact in standalone lesson");
const placeholder = s => /^<[-a-z0-9]+>$/.test(s);
const fields = ["aggregationUnit", "dateFrom", "dateTo", "timeFrom", "timeTo", "daysOfWeek", "isDirectional", "isMetric", "percentiles", "segmentsDirectional"];
const allEvents = ids.flatMap(id => graph.nodes[id].events || []);
const tools = allEvents.filter(e => e.type === "tool");
const posts = tools.filter(e => e.name === "POST /api/v2/traffic/speed-trend");
assert.strictEqual(posts.length, d.roads.length);
posts.forEach((e, i) => {
  assert.deepStrictEqual(Object.keys(e.args).sort(), fields.slice().sort());
  assert.strictEqual(e.args.aggregationUnit, "hour");
  assert.strictEqual(e.args.isMetric, false);
  assert.strictEqual(e.args.isDirectional, true);
  assert.strictEqual(e.args.segmentsDirectional.length, 1);
  assert.strictEqual(e.args.segmentsDirectional[0].segmentId, d.roads[i].code);
  assert.strictEqual(e.args.segmentsDirectional[0].direction, 1);
});
d.roads.forEach(r => {
  assert(placeholder(r.id) && placeholder(r.code) && r.id !== r.code);
  assert(r.validHours <= d.requestedHours && r.validHours >= d.sharedWetHours);
  assert(Math.abs(r.lengthMiles / r.dry * 3600 - r.dryTime) < 1e-8);
  assert(Math.abs(r.lengthMiles / r.rain * 3600 - r.rainTime) < 1e-8);
  assert(r.dryP85 >= r.dryTime && r.rainP85 >= r.rainTime);
  assert(r.dryOver >= 0 && r.rainOver <= 100);
});
assert.strictEqual((Date.parse(d.dateTo) - Date.parse(d.dateFrom)) / 86400000 + 1, 42);
assert.strictEqual(d.requestedHours, 42 * 12);
assert.strictEqual(d.timeFrom, "07:00:00");
assert.strictEqual(d.timeTo, "18:59:59.999");
const geo = tools.find(e => e.name === "POST /api/v2/zones/segments");
assert.strictEqual(geo.args.isMetric, false);
assert.strictEqual(geo.args.radius, d.radiusMiles);
assert(geo.args.roadTypes.includes("trunk"));
assert.strictEqual(geo.args.coordinates.length, d.roads.length);
geo.args.coordinates.forEach(p => assert(typeof p.latitude === "number" && typeof p.longitude === "number"));
const weather = tools.find(e => e.server === "web");
assert.strictEqual(weather.args.timezone, "America/Los_Angeles");
assert.strictEqual(weather.args.hourly, "rain");
assert.strictEqual(weather.args.start_date, d.dateFrom);
assert.strictEqual(weather.args.end_date, d.dateTo);
tools.forEach(e => assert(/Fictional/.test(e.summary) && /Fictional/.test(e.result)));
// Every accepted example job has a matching status and result step.
const api = tools.filter(e => e.server === "altitude-api");
assert.strictEqual(api.length % 3, 0);
for (let i = 0; i < api.length; i += 3) {
  assert(api[i].name.startsWith("POST /api/v2/"));
  assert.strictEqual(api[i + 1].name, "GET /api/v2/jobs/{id}");
  assert.strictEqual(api[i + 2].name, api[i].name.replace("POST ", "GET ") + "/{id}");
  const accepted = JSON.parse(api[i].result.split("\n").slice(1).join("\n"));
  assert.strictEqual(accepted.status, "PENDING");
  assert(placeholder(accepted.id));
  assert.strictEqual(api[i + 1].args.id, accepted.id);
  assert.strictEqual(api[i + 2].args.id, accepted.id);
}
allEvents.filter(e => e.type === "chart").forEach(e => {
  assert(e.title.startsWith("Illustrative · "));
  assert.strictEqual(e.bars.length, 2);
  assert.strictEqual(e.bars[0].color, d.colors.dry);
  assert.strictEqual(e.bars[1].color, d.colors.rain);
  assert(/\(mph\)|\(seconds\)|\(%\)/.test(e.title), "Chart must state its single unit");
});
const maps = allEvents.filter(e => e.type === "map");
assert.strictEqual(maps.length, 2);
const map = maps[0], speedMap = maps[1], frame = d.locator;
const compare = graph.nodes["altitude-compare"].events;
assert.strictEqual(compare[1], speedMap);
assert.strictEqual(speedMap.mapStyle, "altitude-speed-map");
assert.strictEqual(speedMap.image, map.image);
assert.strictEqual(speedMap.scale, map.scale);
assert.strictEqual(speedMap.scaleWidth, map.scaleWidth);
assert(speedMap.title.includes("Fictional") && speedMap.title.includes("mean hourly speed change (mph)"));
assert(speedMap.layerLabel.includes("Modeled rain − matched dry"));
["positive = faster", "negative = slower", "not cause or safety", "not observations", "not vehicles", "returned/measured section boundaries"].forEach(s => assert(speedMap.summary.includes(s)));
assert(speedMap.disclosure.includes("OpenStreetMap") && speedMap.disclosure.includes("ODbL"));
assert.strictEqual(speedMap.pins.length, d.roads.length);
speedMap.pins.forEach((p, i) => {
  const r = d.roads[i], delta = r.rain - r.dry;
  assert.strictEqual(p.label, r.name + " · " + (delta < 0 ? "−" : "+") + Math.abs(delta) + " mph");
  ["x", "y", "flip", "status"].forEach(k => assert.strictEqual(p[k], map.pins[i][k]));
});
assert(compare[0].text.includes("weight the matched rainy hours equally"));
assert(compare[0].text.includes("not an improvement or safety measure"));
assert.strictEqual(compare.filter(e => e.type === "chart").length, 4);
compare.filter(e => e.type === "chart").forEach((e, i) => {
  assert.strictEqual(e.bars[0].value, d.roads[i].dry);
  assert.strictEqual(e.bars[1].value, d.roads[i].rain);
});
["altitude-behavior", "altitude-tail"].forEach(id => assert.strictEqual(graph.nodes[id].events.filter(e => e.type === "chart").length, 2));
assert(graph.nodes["altitude-scope"].events.includes(map));
assert.strictEqual(frame.projection, "EPSG:3857");
assert.strictEqual(map.image, "assets/map-sf-altitude.webp");
assert(fs.statSync(path.join(root, map.image)).size < 300000);
assert(map.disclosure.includes("OpenStreetMap") && map.disclosure.includes("ODbL"));
assert(map.summary.includes("not vehicles") && map.summary.includes("fictional"));
assert.strictEqual(map.pins.length, d.roads.length);
const merc = lat => Math.asinh(Math.tan(lat * Math.PI / 180));
map.pins.forEach((p, i) => {
  const r = d.roads[i];
  assert.strictEqual(p.label, r.name);
  assert.strictEqual(p.status, "locator");
  assert(p.x > 0 && p.x < 100 && p.y > 0 && p.y < 100);
  assert(Math.abs(p.x / 100 * (frame.east - frame.west) + frame.west - r.longitude) < 1e-9);
  assert(Math.abs(merc(frame.north) - p.y / 100 * (merc(frame.north) - merc(frame.south)) - merc(r.latitude)) < 1e-9);
});
assert.strictEqual(d.weatherMatch.dryGuard.length, d.dryGuardHours + 1);
assert.deepStrictEqual(Array.from(d.weatherMatch.dryGuard, h => h.end), ["07:00", "08:00", "09:00"]);
assert.deepStrictEqual(Array.from(d.weatherMatch.dryGuard, h => h.interval), ["06:00–07:00", "07:00–08:00", "08:00–09:00"]);
assert(d.weatherMatch.dryGuard.every(h => h.rain === 0));
assert.strictEqual(d.weatherMatch.weatherEnd, "09:00");
assert.strictEqual(d.weatherMatch.trafficInterval, "08:00–09:00");
const weatherEvents = graph.nodes["altitude-weather"].events;
assert(!weatherEvents.some(e => e.type === "chart"), "Weather matching needs no rainfall chart");
const intervalKey = weatherEvents[4].text;
assert(intervalKey.includes("Illustrative interval key") && intervalKey.includes(d.dryHour.slice(0, 10)) && intervalKey.includes(d.wetHour.slice(0, 10)));
assert(!/numeric badge|bar stub|chart compares|value below/i.test(intervalKey));
const prose = allEvents.map(e => e.text || "").join("\n");
assert(prose.includes("T+1") && prose.includes("T−1") && prose.includes("not confirmation"));
assert(prose.includes("travelSpeedPctOverSpeedLimit"));
assert(prose.includes("not reporting a pooled-trip percentage"));
assert(prose.includes("haven't answered that here"));
assert.strictEqual(d.roads[2].limit, 30);
// Spain's visible decimals remain localized while requests/results stay untouched.
ctx.window.SIM_I18N = {};
["es-419", "es-ES"].forEach(lang => vm.runInContext(fs.readFileSync(path.join(root, "data/i18n/" + lang + ".js"), "utf8"), ctx));
const spanish = ctx.window.SIM_I18N["es-419"].altitude.nodes["altitude-compare"];
assert.strictEqual(spanish.events.length, compare.length);
assert(spanish.events[1].title.includes("Ficticio"));
assert(spanish.events[1].layerLabel.includes("Lluvia modelada − seco emparejado"));
const spainPins = ctx.window.SIM_I18N["es-ES"].altitude.nodes["altitude-compare"].events[1].pins;
spainPins.forEach((label, i) => assert.strictEqual(label, speedMap.pins[i].label.replace(".", ",")));
assert(spainPins[2].includes("−1,5 mph"));
console.log("[check-altitude] isolated graphs, fictional fixtures, REST jobs, units, clock/matching disclosures and charts passed.");
